def context(hour: int, weekday: int, music: bool, temp: float | None, rain: bool, app: str, idle_s: float,
            work_s: float, month: int = 0) -> list[str]:
    """Темы, подходящие сейчас: время суток, погода, музыка, чем занят хозяин. Общие темы есть всегда."""
    topics = ["friendship", "jokes", "dreams", "science", "food", "user", "space", "animals", "secrets",
              "compliments", "riddles", "tales", "mood"]
    topics += (["night"] if hour >= 22 or hour < 5 else ["morning"] if hour < 11 else ["day"] if hour < 17
               else ["evening"])
    if music:
        topics += ["music"] * 3
    if rain:
        topics += ["rain"] * 2
    if temp is not None and temp <= 0:
        topics += ["cold"] * 2
    if temp is not None and temp >= 28:
        topics += ["hot"] * 2
    if month in (12, 1, 2):
        topics.append("winter")
    elif month in (6, 7, 8):
        topics.append("summer")
    if weekday >= 5:
        topics.append("weekend")
    if weekday == 4:
        topics.append("friday")
    app = app.lower()
    if any(w in app for w in ("code", "pycharm", "studio", "terminal", "cursor", "idea")):
        topics += ["code"] * 2
    elif any(w in app for w in ("youtube", "netflix", "кинопоиск", "vlc", "twitch")):
        topics += ["video"] * 2
    elif any(w in app for w in ("telegram", "whatsapp", "discord")):
        topics.append("chat")
    elif any(w in app for w in ("steam", ".exe game", "cs2", "dota", "minecraft", "roblox")):
        topics += ["games"] * 2
    if idle_s > 120:
        topics += ["idle"] * 2
    elif work_s > 45 * 60:
        topics += ["work"] * 2
    return topics


def pick(topics: list[str], recent: list[str]) -> tuple[str, list[tuple[str, str, str]]]:
    """Тема и разговор, по возможности не из недавних (чтобы не повторялись)."""
    fresh = [t for t in topics if t not in recent[-3:]] or topics
    topic = random.choice(fresh)
    return topic, random.choice(TOPICS[topic])


def next_pause(hour: int, idle_s: float, rng: random.Random | None = None) -> float:
    """Через сколько секунд следующая сценка. Как у живых: иногда болтают подряд, иногда надолго замолкают.
    Ночью и пока хозяин сосредоточенно печатает — реже."""
    r = rng or random
    roll = r.random()
    if roll < 0.2:
        pause = r.uniform(12, 30)          # «а ещё…» — продолжают почти сразу
    elif roll < 0.75:
        pause = r.uniform(45, 160)
    elif roll < 0.95:
        pause = r.uniform(180, 420)        # задумались, молчат
    else:
        pause = r.uniform(480, 900)        # совсем притихли
    if hour >= 23 or hour < 6:
        pause *= 1.8
    if idle_s < 3:                          # хозяин прямо сейчас печатает или двигает мышь — не отвлекать
        pause *= 1.4
    return pause


def today() -> tuple[int, int]:
    now = datetime.datetime.now()
    return now.hour, now.weekday()
